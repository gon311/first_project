package com.itwillbs.project.my.dto;

import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.ToString;

/* =========================================================
 * ✅ MyPage DTO 설계 템플릿 (화면정의서/JSP 기준)
 *
 * [목표]
 *  - "전체 USER DTO"와 섞지 말고, 마이페이지 화면에서 필요한 값만 얇게 담는다.
 *  - 페이지별로 DTO를 쪼개도 되고(권장), 처음엔 MyDTO 하나로 시작해도 된다.
 *  - 처음엔 주석 블록만 만들어두고, 작업하면서 필요한 필드만 추가한다.
 *
 * ---------------------------------------------------------
 * ✅ 작업 순서 추천 (실제로 이렇게 하면 안 꼬임)
 *  1) JSP 뼈대 + 샘플 데이터(하드코딩)로 화면 완성
 *  2) 화면정의서 요구사항을 "표에 표시되는 필드"로 쪼개기
 *  3) DTO에 (표/카드/버튼에 필요한) 최소 필드만 추가
 *  4) MyBatis Mapper 결과 컬럼 = DTO 필드명으로 맞추기
 *  5) 컨트롤러에서 model.addAttribute로 JSP에 전달
 *
 * ---------------------------------------------------------
 * ✅ DTO 블록 설계 규칙
 *  - [A] 화면에 안 쓰는 값은 넣지 않는다
 *  - [B] 수정/저장 요청 DTO는 조회 DTO와 분리한다 (보안/유효성)
 *  - [C] "리스트(목록) DTO"는 1줄 렌더에 필요한 값만 담는다
 *  - [D] 날짜/금액/상태는 일단 String/Integer로 시작 → 안정화 후 타입 개선
 *
 * ---------------------------------------------------------
 * ✅ (공통) 페이지 상단/사이드바/세션 사용자 표시용
 *  - JSP에서 loginUser.name/email/phone 같은 표시에 쓰는 최소 값
 *  - 이미 UserDTO가 있다면 굳이 여기 넣지 말고, "필요 시만" 복제
 * ---------------------------------------------------------
 * [공통-표시]
 *  - userId
 *  - name
 *  - email
 *  - phone
 *  - userType(P/C)
 *
 * ---------------------------------------------------------
 * ✅ (요청) 내정보 수정 Request DTO로 분리 권장
 * ---------------------------------------------------------
 * [내정보-수정 요청]
 *  - email(식별/readonly여도 where 조건으로 사용 가능)
 *  - name
 *  - phone
 *
 * ---------------------------------------------------------
 * ✅ (목록) 이력서 관리(myResume.jsp) - 리스트 1줄에 필요한 값
 * ---------------------------------------------------------
 * [이력서-목록]
 *  - resumeId
 *  - title
 *  - status(DRAFT/COMPLETE)
 *  - representative(true/false)
 *  - updatedAt
 *
 * (선택) 화면에서 보여주면 추가
 *  - careerType(신입/경력)
 *  - desiredJob / desiredRegion
 *
 * ---------------------------------------------------------
 * ✅ (목록) 자소서 관리(myReview.jsp) - 리스트 1줄에 필요한 값
 * ---------------------------------------------------------
 * [자소서-목록]
 *  - reviewId
 *  - title
 *  - companyName
 *  - status(DRAFT/COMPLETE)
 *  - representative(true/false)
 *  - updatedAt
 *
 * ---------------------------------------------------------
 * ✅ (목록) 관심목록(favorites) - 공고 카드/행에 필요한 값
 * ---------------------------------------------------------
 * [관심공고-목록]
 *  - favoriteId
 *  - jobId
 *  - companyName
 *  - title
 *  - location / career / education / employmentType
 *  - deadline
 *  - canApply(버튼 활성/비활성)
 *
 * ---------------------------------------------------------
 * ✅ (목록) 지원내역(apply) - 1행에 필요한 값
 * ---------------------------------------------------------
 * [지원내역-목록]
 *  - appId
 *  - jobId
 *  - companyName
 *  - title
 *  - appliedAt
 *  - status
 *
 * ---------------------------------------------------------
 * ✅ (목록) 결제내역(payment) - 테이블 1행에 필요한 값
 * ---------------------------------------------------------
 * [결제내역-목록]
 *  - paymentId
 *  - paidAt
 *  - productName
 *  - amount
 *  - method
 *  - status(PAID/UNPAID/FREE/REFUND 등)
 *
 * ---------------------------------------------------------
 * ✅ (목록) 추천공고(recommend) - 리스트 1행 + 버튼에 필요한 값
 * ---------------------------------------------------------
 * [추천공고-목록]
 *  - jobId
 *  - companyName
 *  - title
 *  - meta(경력/학력/지역/고용형태 등)
 *  - deadline(오늘마감 등 표시용)
 *  - canApply
 *  - reasonTag(“선호 공고” 같은 라벨)
 *
 * ---------------------------------------------------------
 * ✅ 화면정의서 요구사항을 DTO로 옮길 때 체크리스트
 *  - [표/카드에서 실제로 보이는 텍스트]만 필드로 만든다
 *  - [버튼 조건]이 있으면 boolean 필드로 분리한다
 *  - [상태값]은 enum 대신 String으로 시작(빠르게) → 나중에 enum화
 *  - [상세 페이지]가 있으면 목록 DTO + 상세 DTO를 분리한다
 * ========================================================= */

// -----------------------------------------------------------------

@Getter
@Setter
@ToString
@NoArgsConstructor
public class MyDTO {
	private Long userId; // 회원 ID
	private String userName; // 회원 이름
	private String email; // 이메일
	private String phone; // 전화번호
	private String userType; // 회원 상태 "P" or "C"


}

